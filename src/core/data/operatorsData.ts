export function getOperatorSuggestions(isCollectionContext: boolean = false): readonly BloggerSuggestion[] {
  return Object.values(bloggerOperatorsCatalog)
    .filter(op => !isCollectionContext || op.isCollectionOperator)
    .map(op => ({
      name: op.name,
      type: (op.returnType === 'same' || op.returnType === 'element') ? 'object' : op.returnType,
      kind: 'property' as const,
      detail: `(Blogger ${op.isCollectionOperator ? 'Collection ' : ''}Operator)`,
      description: `${op.description}\n\n**Syntax:** \`${op.signature}\``,
      example: op.example,
      docUrl: op.docUrl,
    }));
}
