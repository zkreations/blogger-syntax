export function getWidgetSettingsSuggestions(widgetType?: string): readonly BloggerSuggestion[] {
  if (!widgetType) {
    return [];
  }
  const settings = widgetSettingsCatalog[widgetType];
  if (!settings) {
    return [];
  }
  return Object.values(settings).map((setting): BloggerSuggestion => ({
    name: setting.name,
    type: 'string' as BloggerDataType,
    kind: 'property',
    detail: `(${widgetType} Setting)`,
    description: setting.description,
    example: `<b:widget-setting name="${setting.name}">${setting.default ?? ''}</b:widget-setting>`,
  }));
}
